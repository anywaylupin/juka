/**
 * Writes public/favicon.svg: the 卡 seal, the app's mark.
 *
 * 卡 is the second half of 橘卡 and means card, cut as a red chop in a block a little wider than it is tall, close to square without being one, the way an index card reads when it is stamped small.
 * The in-app logo is the same seal drawn in CSS by AppLogo, where the brush font is loaded; a favicon cannot load a web font, so here the character is text in the system's kai face.
 * The seal is two rectangles, not icon path data, so nothing here is drawn by hand.
 *
 * Run after changing a color or the proportions:
 *
 *   node scripts/build-favicon.ts
 */
import { writeFile } from 'node:fs/promises';

const SEAL = '#c8392b';
const PAPER = '#fff8f0';

/** 44 by 38 in a 48 box: wider than tall by about the step from a square toward the 5 by 3.2 card. */
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48">
  <!-- Generated by scripts/build-favicon.ts. -->
  <rect x="2" y="5" width="44" height="38" rx="6" fill="${SEAL}"/>
  <rect x="5.5" y="8.5" width="37" height="31" rx="3" fill="none" stroke="${PAPER}" stroke-opacity="0.6" stroke-width="1.2"/>
  <text x="24" y="34.5" text-anchor="middle" font-size="27" font-weight="700" fill="${PAPER}" font-family="'Ma Shan Zheng', KaiTi, STKaiti, 'Kaiti SC', 'Noto Serif SC', serif">卡</text>
</svg>
`;

await writeFile('public/favicon.svg', svg, 'utf8');
console.log('Wrote public/favicon.svg');
