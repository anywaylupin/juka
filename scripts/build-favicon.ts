/**
 * Writes public/favicon.svg from an icon in the installed sets.
 *
 * The icon is lifted from `@iconify-json/icon-park-outline` and recolored, not redrawn here.
 * That is the rule for every icon in this app: they come from a set so they stay consistent with each other and so nobody has to maintain hand written path data.
 *
 * Run after changing ICON or COLOR:
 *
 *   node scripts/build-favicon.ts
 */
import { readFile, writeFile } from 'node:fs/promises';

/** The same mandarin the rating uses, filled, with 橘 written on it: the app's name on its own fruit. */
const ICON = 'orange';
const PEEL = '#f5821f';
const LEAF = '#3f8f3a';
const INK = '#fff8f0';
const SET = 'node_modules/@iconify-json/icon-park-outline/icons.json';

interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

const set: IconSet = JSON.parse(await readFile(SET, 'utf8'));
const icon = set.icons[ICON];

if (!icon) {
  throw new Error(`Icon "${ICON}" is not in ${SET}`);
}

const width = icon.width ?? set.width ?? 24;
const height = icon.height ?? set.height ?? 24;

/**
 * IconPark draws the fruit as two stroked paths, the peel and the calyx, plus four dots for the pores.
 * The peel is filled and stroked in tangerine, the calyx goes green, and the dots are dropped because 橘 sits where they were.
 */
const paths = [...icon.body.matchAll(/<path[^>]*\/>/g)].map((match) => match[0]);
const [peel, calyx] = paths;

if (!peel || !calyx) {
  throw new Error(`Icon "${ICON}" no longer has the peel and calyx paths this script expects`);
}

const fruit = [
  peel.replace('stroke="currentColor"', `stroke="${PEEL}" fill="${PEEL}"`),
  calyx.replace('stroke="currentColor"', `stroke="${LEAF}" fill="${LEAF}"`)
].join('\n  ');

const head = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <!-- Generated by scripts/build-favicon.ts from icon-park-outline "${ICON}" (MIT). Recolored, not redrawn. -->
  ${fruit}`;

/**
 * The favicon carries the character as text, in the system's kai face, because a favicon cannot load a web font.
 * The app's own logo uses mandarin.svg, the fruit alone, and writes 橘 over it in the brush font.
 */
const favicon = `${head}
  <text x="24" y="35" text-anchor="middle" font-size="20" font-weight="700" fill="${INK}" font-family="'Ma Shan Zheng', KaiTi, STKaiti, 'Kaiti SC', serif">橘</text>
</svg>
`;

await writeFile('public/favicon.svg', favicon, 'utf8');
await writeFile('public/mandarin.svg', `${head}\n</svg>\n`, 'utf8');
console.log(`Wrote public/favicon.svg and public/mandarin.svg from icon-park-outline "${ICON}"`);
